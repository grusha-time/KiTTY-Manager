Зашифрованный config.json следует открывать той же учётной записью Windows на том же компьютере. Для переноса на другую учётную запись или компьютер используйте «Экспорт JSON…»: экспорт переносим, но его секреты хранятся открытым текстом, поэтому удалите файл после импорта и не передавайте посторонним.

Менеджер расшифровывает значения только в памяти перед использованием. При явной записи в KiTTY пароли преобразуются в штатный формат portable-сессии KiTTY; исходный config.json при этом остаётся зашифрованным.

